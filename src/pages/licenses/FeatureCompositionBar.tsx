/**
 * แถบส่วนประกอบของชุดสิทธิ์ — เศษของแค็ตตาล็อกทั้งหมดที่ชุดนี้กินไป
 *
 * ตัวหารมาจากผู้เรียกโดยตั้งใจ ไม่คำนวณเองจาก `count` ที่มากที่สุดในหน้า: ถ้าแต่ละแถวย่อ/ขยาย
 * แกนตามข้อมูลของตัวเอง แถบสองแถบที่ยาวเท่ากันจะหมายถึงคนละจำนวน ซึ่งแย่กว่าไม่มีแถบเลย
 * (บทเรียนเดียวกับ `windowStart`/`windowEnd` ของ LicenseCoverageBar)
 *
 * ตัวหารเป็น `null` ได้ = แค็ตตาล็อกโหลดไม่สำเร็จ ผู้เรียกต้องไม่วาดแถบเลย ไม่ใช่ตกไปใช้ตัวหาร
 * สำรอง เพราะนั่นทำให้ความยาวของแถบเปลี่ยนความหมายไปเงียบ ๆ
 *
 * คอลัมน์ที่ถือแถบนี้ต้องกว้างคงที่ (`w-56`) — แกนร่วมคือทั้งหมดของแถบ ถ้าความกว้างคอลัมน์
 * ยืดตามเนื้อหา แถวที่ยาวเท่ากันบนจอจะเลิกหมายถึงจำนวนเท่ากัน
 */
export function FeatureCompositionBar({
  count, total, label,
}: { count: number; total: number; label: string }) {
  const pct = total > 0 ? Math.min(100, (count / total) * 100) : 0;
  return (
    <div
      className="bg-foreground/10 h-1.5 w-full overflow-hidden rounded-full"
      role="img"
      aria-label={label}
      title={label}
    >
      <div
        className="bg-primary h-full rounded-full"
        // ชุดที่มีสิทธิ์เดียวจากร้อยกว่าตัวจะได้แถบ <1% ซึ่งมองไม่เห็น — ยกพื้นไว้ที่ 1.5%
        // "มีนิดเดียว" กับ "ไม่มีเลย" ต้องอ่านต่างกัน
        style={{ width: count > 0 ? `${Math.max(pct, 1.5)}%` : '0%' }}
      />
    </div>
  );
}
